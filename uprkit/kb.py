"""python -m uprkit kb - the knowledge base of field notes (knowledge/).

    python -m uprkit kb list                          every note: category, title, summary
    python -m uprkit kb search WORD [WORD ...]        notes that contain all the words (case-insensitive)
    python -m uprkit kb new CATEGORY SLUG "TITLE"     a new note from knowledge/TEMPLATE.md
    python -m uprkit kb index [--check]               rewrite knowledge/INDEX.md (--check: only report if stale)
    python -m uprkit kb check                         every note has the template's fields and sections; ASCII only

A note is one lesson that transfers to other games: symptom, cause, rule, evidence. Notes are written per hardware
topic, per workflow step or per engine / middleware CATEGORY - never about one named game (skills/field-notes).
"""
import argparse
import os
import re
import sys

from . import find_dir

CATEGORIES = {
    "hardware": "the PSP (and PS2) hardware as measured",
    "translation": "analysis and translation of PS2 code",
    "hle": "replacing PS2 kernel, libraries and devices",
    "engines": "engine and middleware categories (never a product or game name)",
    "workflow": "testing, deploying, measuring, working with the user",
}
FIELDS = ("Category", "Summary", "Applies to", "Evidence", "Status")
SECTIONS = ("Situation", "Cause", "Rule", "Evidence", "Related")
SLUG_RX = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


def kb_dir():
    return find_dir("knowledge")


def notes(root=None):
    """[dict(path, rel, category, title, fields, sections, text)] of every note (not README/TEMPLATE/INDEX)."""
    root = root or kb_dir()
    out = []
    for cat in sorted(os.listdir(root)) if os.path.isdir(root) else []:
        d = os.path.join(root, cat)
        if not os.path.isdir(d):
            continue
        for fn in sorted(os.listdir(d)):
            if not fn.endswith(".md"):
                continue
            p = os.path.join(d, fn)
            with open(p, encoding="utf-8") as f:
                text = f.read()
            m = re.search(r"^# (.+)$", text, re.M)
            fields = dict(re.findall(r"^- \*\*([A-Za-z ]+):\*\* *(.*)$", text, re.M))
            sections = re.findall(r"^## (.+?)\s*$", text, re.M)
            out.append(dict(path=p, rel="%s/%s" % (cat, fn), category=cat, title=m.group(1).strip() if m else fn,
                            fields=fields, sections=sections, text=text))
    return out


def render_index(ns):
    lines = ["# Knowledge base index", "",
             "Generated by `python -m uprkit kb index` - do not edit by hand. Search: `python -m uprkit kb search WORDS`.",
             ""]
    for cat, what in CATEGORIES.items():
        rows = [n for n in ns if n["category"] == cat]
        lines += ["## %s (%s)" % (cat, what), ""]
        if not rows:
            lines += ["No notes yet.", ""]
            continue
        for n in rows:
            lines.append("- [%s](%s) - %s" % (n["title"], n["rel"], n["fields"].get("Summary", "").strip()))
        lines.append("")
    other = sorted(set(n["category"] for n in ns) - set(CATEGORIES))
    for cat in other:
        lines += ["## %s" % cat, ""] + ["- [%s](%s) - %s" % (n["title"], n["rel"], n["fields"].get("Summary", ""))
                                        for n in ns if n["category"] == cat] + [""]
    return "\n".join(lines).rstrip() + "\n"


def index_path():
    return os.path.join(kb_dir(), "INDEX.md")


def index_current():
    p = index_path()
    if not os.path.exists(p):
        return False
    with open(p, encoding="utf-8") as f:
        return f.read() == render_index(notes())


def problems():
    bad = []
    ns = notes()
    for n in ns:
        if n["category"] not in CATEGORIES:
            bad.append((n["rel"], "unknown category folder (one of: %s)" % ", ".join(CATEGORIES)))
        for k in FIELDS:
            if not n["fields"].get(k, "").strip():
                bad.append((n["rel"], "field '- **%s:**' missing or empty" % k))
        if n["fields"].get("Category", "").strip() not in ("", n["category"]):
            bad.append((n["rel"], "Category field differs from the folder"))
        for s in SECTIONS:
            if s not in n["sections"]:
                bad.append((n["rel"], "section '## %s' missing" % s))
        for ln, line in enumerate(n["text"].split("\n"), 1):
            if any(ord(c) > 126 for c in line):
                bad.append((n["rel"], "line %d: non-ASCII character (house style: plain ASCII)" % ln))
                break
        if re.search(r"(?i)(?<![a-z0-9_])[a-z]:[\\/]", n["text"]):
            bad.append((n["rel"], "a drive-letter path (a path of someone's machine)"))
    if not index_current():
        bad.append(("INDEX.md", "stale: run python -m uprkit kb index"))
    return bad


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python -m uprkit kb", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="action", required=True)
    sub.add_parser("list")
    s = sub.add_parser("search")
    s.add_argument("words", nargs="+")
    n = sub.add_parser("new")
    n.add_argument("category", choices=sorted(CATEGORIES))
    n.add_argument("slug")
    n.add_argument("title")
    i = sub.add_parser("index")
    i.add_argument("--check", action="store_true")
    sub.add_parser("check")
    a = ap.parse_args(argv)

    if a.action == "list":
        for x in notes():
            print("%-12s %-60s %s" % (x["category"], x["title"][:60], x["fields"].get("Summary", "")[:80]))
        return 0
    if a.action == "search":
        words = [w.lower() for w in a.words]
        hits = []
        for x in notes():
            low = x["text"].lower()
            if all(w in low for w in words):
                lines = [ln.strip() for ln in x["text"].split("\n") if any(w in ln.lower() for w in words)]
                hits.append((sum(low.count(w) for w in words), x, lines))
        for score, x, lines in sorted(hits, key=lambda h: -h[0]):
            print("knowledge/%s  (%s)" % (x["rel"], x["title"]))
            for ln in lines[:3]:
                print("    " + ln[:150])
        if not hits:
            print("no note contains all of: %s" % " ".join(a.words))
        return 0 if hits else 1
    if a.action == "new":
        if not SLUG_RX.match(a.slug):
            print("slug: lowercase words joined by '-'", file=sys.stderr)
            return 2
        dst = os.path.join(kb_dir(), a.category, a.slug + ".md")
        if os.path.exists(dst):
            print("exists: %s" % dst, file=sys.stderr)
            return 1
        with open(os.path.join(kb_dir(), "TEMPLATE.md"), encoding="utf-8") as f:
            t = f.read()
        t = re.sub(r"^# .*$", "# " + a.title, t, count=1, flags=re.M)
        t = re.sub(r"^- \*\*Category:\*\*.*$", "- **Category:** " + a.category, t, count=1, flags=re.M)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w", encoding="utf-8", newline="\n") as f:
            f.write(t)
        print("new note: %s (fill it in, then: python -m uprkit kb index && python -m uprkit kb check)" % dst)
        return 0
    if a.action == "index":
        if a.check:
            ok = index_current()
            print("INDEX.md is %s" % ("current" if ok else "stale: run python -m uprkit kb index"))
            return 0 if ok else 1
        with open(index_path(), "w", encoding="utf-8", newline="\n") as f:
            f.write(render_index(notes()))
        print("wrote %s (%d notes)" % (index_path(), len(notes())))
        return 0
    bad = problems()
    for rel, msg in bad:
        print("FAIL %s: %s" % (rel, msg))
    print("%d notes, %d problems" % (len(notes()), len(bad)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
